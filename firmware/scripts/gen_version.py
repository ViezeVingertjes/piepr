# PlatformIO pre-build script: git describe -> src/version_gen.h, on every build
# (ESP-IDF's own app version is only refreshed when CMake reconfigures).
import os
import subprocess
import sys

Import("env")  # noqa: F821  (provided by PlatformIO)
sys.path.insert(0, env.subst("$PROJECT_DIR/scripts"))  # noqa: F821
from gen_common import c_string, write_if_changed  # noqa: E402

PROJECT = env.subst("$PROJECT_DIR")  # noqa: F821

try:
    version = subprocess.check_output(
        ["git", "describe", "--always", "--dirty", "--tags"],
        cwd=PROJECT, stderr=subprocess.DEVNULL, text=True,
    ).strip()
except (OSError, subprocess.CalledProcessError):
    version = "unknown"

write_if_changed(
    os.path.join(PROJECT, "src", "version_gen.h"),
    "/* Generated by scripts/gen_version.py - do not edit or commit. */\n"
    "#pragma once\n"
    "#define FW_VERSION " + c_string(version) + "\n",
)
